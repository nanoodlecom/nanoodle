#!/usr/bin/env node
// Generate classic scripts for the sandboxed player and self-contained HTML.
// Run with esbuild 0.28.2 on PATH (or set ESBUILD to that executable).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const compiler = process.env.ESBUILD || "esbuild";
const version = "0.28.2";
const scene = "vendor/rotoscope-render3d/";
const hash = (...values) => {
  const digest = createHash("sha256");
  for (const value of values) digest.update(value);
  return digest.digest("hex");
};
const bundles = [
  {
    entry: "vendor/rotoscope-local.mjs", output: "vendor/rotoscope-player.js",
    global: "NoodleRotoscopeLocal", dependencies: [],
    options: ["--log-override:empty-import-meta=silent"],
  },
  {
    entry: scene + "scene.mjs", output: "vendor/rotoscope-player-scene.js",
    global: "NoodleRender3dScene",
    dependencies: ["three.module.js", "addons/loaders/GLTFLoader.js", "addons/environments/RoomEnvironment.js",
      "addons/utils/BufferGeometryUtils.js"].map(name => scene + name),
    options: ["--alias:three=./" + scene + "three.module.js"],
  },
];

if (!check && execFileSync(compiler, ["--version"], { encoding: "utf8" }).trim() !== version) {
  throw new Error("Expected esbuild " + version);
}
for (const { entry, output, global, dependencies, options } of bundles) {
  const inputs = hash(readFileSync(new URL(import.meta.url)), ...[entry, ...dependencies].map(name => readFileSync(root + name)));
  if (check) {
    const file = readFileSync(root + output, "utf8");
    const line = file.indexOf("\n");
    const payload = file.slice(line + 1);
    if (file.slice(0, line) !== header(inputs, payload)) throw new Error(output + " is stale. Run scripts/gen-rotoscope-player.mjs");
  } else {
    const payload = execFileSync(compiler, [entry, "--bundle", "--format=iife", "--minify", "--target=es2022",
      "--global-name=globalThis." + global, ...options], { cwd: root, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 });
    writeFileSync(root + output, header(inputs, payload) + "\n" + payload);
  }
}

function header(inputs, payload) {
  return "/* Generated by scripts/gen-rotoscope-player.mjs. " + inputs + " " + hash(payload) + " */";
}
